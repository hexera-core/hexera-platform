"""A branching microchannel network following Murray's law, built as a real B-rep solid.

WHY MURRAY'S LAW. Corintis's channels are described as bio-inspired and branching, generated by
topology optimisation, which means the exact shape differs on every design and nobody outside the
company has one. What does NOT differ is the rule that governs how a branching flow network sizes its
children, and that rule is Murray's law: for laminar flow, the cube of the parent radius equals the sum
of the cubes of the child radii. It is the law vascular trees follow, the one the "bio-inspired"
description is pointing at, and it produces the right KIND of geometry to stress a mesher: many
generations, widely varying channel widths in one part, and junctions where three passages meet.

For a symmetric bifurcation the law gives r_child = r_parent / 2^(1/3), a factor of 0.7937 per
generation. Starting at a 300 um trunk, four generations land at 119 um, which brackets Corintis's
published 90 to 371 um range.

WHAT THIS IS AND IS NOT. It is a parametric test article with known dimensions, suitable for measuring
mesher behaviour and for checking that a pipeline survives branching topology. It is NOT a replica of
any Corintis part and must never be presented as one.

UNITS ARE MILLIMETRES throughout, which is OpenCASCADE's convention and also the frame in which a 90 um
feature is 0.09, comfortably inside the range where tessellation and solid predicates behave. The same
shape built in metres fails: trimesh returns is_volume False for a cylinder of radius 2e-4 because the
end caps collapse.
"""
from __future__ import annotations

import math
from dataclasses import dataclass

MURRAY_RATIO = 2.0 ** (-1.0 / 3.0)   # 0.79370, the symmetric-bifurcation child/parent radius ratio


@dataclass(frozen=True)
class MurraySpec:
    """Every dimension of the network. All lengths in millimetres."""
    trunk_width_mm: float = 0.300      # 300 um trunk, matching the published tapering range
    generations: int = 4               # 300 -> 238 -> 189 -> 150 -> 119 um
    depth_mm: float = 0.800            # Corintis's published channel-layer thickness
    first_length_mm: float = 4.0       # trunk run before the first split
    length_ratio: float = 0.72         # each generation is shorter than its parent
    branch_half_angle_deg: float = 28.0
    wall_mm: float = 0.120             # solid wall around the network, so it is a closed part

    def width(self, generation: int) -> float:
        """Channel width at a generation, 0 being the trunk."""
        return self.trunk_width_mm * (MURRAY_RATIO ** generation)

    def length(self, generation: int) -> float:
        return self.first_length_mm * (self.length_ratio ** generation)

    @property
    def narrowest_mm(self) -> float:
        return self.width(self.generations)

    def segments(self) -> int:
        """Total channel segments: 1 + 2 + 4 + ... = 2^(g+1) - 1."""
        return 2 ** (self.generations + 1) - 1

    def describe(self) -> str:
        w = ", ".join(f"{self.width(g)*1e3:.1f}" for g in range(self.generations + 1))
        return (f"Murray tree, {self.generations} generations, {self.segments()} segments\n"
                f"  widths (um): {w}\n"
                f"  depth {self.depth_mm*1e3:.0f} um, narrowest {self.narrowest_mm*1e3:.1f} um, "
                f"wall {self.wall_mm*1e3:.0f} um")


def _centrelines(spec: MurraySpec) -> list[tuple[tuple[float, float], tuple[float, float], int]]:
    """Every segment as (start, end, generation), laid out in the xy plane.

    Grown breadth-first from a trunk running in +y at the origin. Each bifurcation splits the incoming
    direction by the half-angle, so the tree fans out symmetrically.
    """
    half = math.radians(spec.branch_half_angle_deg)
    out: list[tuple[tuple[float, float], tuple[float, float], int]] = []
    # (start point, direction angle from +x axis, generation)
    frontier: list[tuple[tuple[float, float], float, int]] = [((0.0, 0.0), math.pi / 2.0, 0)]
    while frontier:
        (x, y), ang, g = frontier.pop(0)
        if g > spec.generations:
            continue
        L = spec.length(g)
        ex, ey = x + L * math.cos(ang), y + L * math.sin(ang)
        out.append(((x, y), (ex, ey), g))
        if g < spec.generations:
            frontier.append(((ex, ey), ang - half, g + 1))
            frontier.append(((ex, ey), ang + half, g + 1))
    return out


def build(spec: MurraySpec | None = None):
    """Return (solid_part, fluid_network, spec).

    `fluid_network` is the channel volume: the union of a rounded slab per segment plus a disc at every
    junction, so neighbouring segments merge without a crack at the joint. Junction discs are what stop
    a boolean union leaving a sliver face where two capsules meet at an angle.

    `solid_part` is a block around it with the fluid cut out, which is the monolithic arrangement
    Corintis describes: channels enclosed inside one piece rather than a plate with a lid on top.
    """
    from OCP.BRepAlgoAPI import BRepAlgoAPI_Cut, BRepAlgoAPI_Fuse
    from OCP.BRepPrimAPI import BRepPrimAPI_MakeBox, BRepPrimAPI_MakeCylinder
    from OCP.gp import gp_Ax2, gp_Dir, gp_Pnt

    spec = spec or MurraySpec()
    segs = _centrelines(spec)
    z0, dz = 0.0, spec.depth_mm

    pieces = []
    for (sx, sy), (ex, ey), g in segs:
        w = spec.width(g)
        r = w / 2.0
        dx, dy = ex - sx, ey - sy
        L = math.hypot(dx, dy)
        ang = math.atan2(dy, dx)
        # the straight run as a box, rotated into place by building it along +x then transforming
        box = BRepPrimAPI_MakeBox(gp_Pnt(0.0, -r, z0), L, w, dz).Shape()
        from OCP.gp import gp_Trsf, gp_Ax1
        from OCP.BRepBuilderAPI import BRepBuilderAPI_Transform
        t = gp_Trsf()
        t.SetRotation(gp_Ax1(gp_Pnt(0, 0, 0), gp_Dir(0, 0, 1)), ang)
        rotated = BRepBuilderAPI_Transform(box, t, True).Shape()
        t2 = gp_Trsf()
        t2.SetTranslation(gp_Pnt(0, 0, 0), gp_Pnt(sx, sy, 0))
        placed = BRepBuilderAPI_Transform(rotated, t2, True).Shape()
        pieces.append(placed)
        # a disc at each end, radius = half width, so joints fuse cleanly
        for (px, py) in ((sx, sy), (ex, ey)):
            cyl = BRepPrimAPI_MakeCylinder(
                gp_Ax2(gp_Pnt(px, py, z0), gp_Dir(0, 0, 1)), r, dz).Shape()
            pieces.append(cyl)

    fluid = pieces[0]
    for p in pieces[1:]:
        fluid = BRepAlgoAPI_Fuse(fluid, p).Shape()

    from OCP.Bnd import Bnd_Box
    from OCP.BRepBndLib import BRepBndLib
    bb = Bnd_Box()
    BRepBndLib.Add_s(fluid, bb)
    # OCP 8 does not expose Bnd_Box::Limits to Python, so Get() raises. CornerMin/CornerMax return
    # gp_Pnt and work on every version.
    lo, hi = bb.CornerMin(), bb.CornerMax()
    xmin, ymin, zmin = lo.X(), lo.Y(), lo.Z()
    xmax, ymax, zmax = hi.X(), hi.Y(), hi.Z()
    m = spec.wall_mm
    block = BRepPrimAPI_MakeBox(
        gp_Pnt(xmin - m, ymin - m, zmin - m),
        (xmax - xmin) + 2 * m, (ymax - ymin) + 2 * m, (zmax - zmin) + 2 * m).Shape()
    solid = BRepAlgoAPI_Cut(block, fluid).Shape()
    return solid, fluid, spec


def analytic_fluid_volume(spec: MurraySpec) -> float:
    """An UPPER bound on the fluid volume: every segment and disc counted without subtracting overlaps.

    Deliberately an upper bound rather than an estimate. The true union is smaller because segments and
    their end discs overlap at every junction, so the measured volume must be below this and within
    about 10 per cent of it. A measured volume ABOVE this number means the boolean union failed and
    produced something larger than its own parts, which is a real failure mode worth catching.
    """
    total = 0.0
    for g in range(spec.generations + 1):
        n = 2 ** g
        w = spec.width(g)
        total += n * (spec.length(g) * w * spec.depth_mm)        # straight runs
        total += n * 2 * (math.pi * (w / 2.0) ** 2 * spec.depth_mm)  # two discs each
    return total
